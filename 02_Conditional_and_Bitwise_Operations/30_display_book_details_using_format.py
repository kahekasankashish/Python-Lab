# Q30. Create and print a formatted book structure with name, publication, ISBN, author, total pages and price.
book_name = input("Enter book name: ")
publication = input("Enter publication: ")
isbn = input("Enter ISBN number: ")
author = input("Enter author: ")
total_pages = int(input("Enter total pages: "))
price = float(input("Enter price: "))
print("----- Book Details -----")
print("{:<14}: {}".format("Book Name", book_name))
print("{:<14}: {}".format("Publication", publication))
print("{:<14}: {}".format("ISBN No", isbn))
print("{:<14}: {}".format("Author", author))
print("{:<14}: {}".format("Total Pages", total_pages))
print("{:<14}: ₹{:.2f}".format("Price", price))
